// world/bundle.mjs — the deterministic ES-module concatenator for world.html.
//
// There is no npm install in this repo, so instead of a real bundler we lean on
// a property of the vendored files: every one is a flat ES module whose only
// imports are `from 'three'` or a relative addon path, and whose only export is
// a single trailing `export { ... };`. Strip those statements and the bodies can
// simply be concatenated in dependency order.
//
// Three.js itself lands at top level (its ~380 exports become module-scope
// bindings). Each addon and our own runtime go inside an IIFE so their private
// top-level names can never collide with three's, while still closing over it.

const BUNDLE_IMPORT_START = /^\s*import\b/;
const BUNDLE_IMPORT_END = /from\s+['"][^'"]+['"]\s*;?\s*$/;
const BUNDLE_SIDE_EFFECT = /^\s*import\s+['"][^'"]+['"]\s*;?\s*$/;
const BUNDLE_EXPORT_LIST = /^\s*export\s*\{([^}]*)\}\s*;?\s*$/;
const BUNDLE_EXPORT_DEFAULT = /^\s*export\s+default\b/;
const BUNDLE_EXPORT_DECL = /^(\s*)export\s+(async\s+function|function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/;

/**
 * Remove ES module syntax from a source file, collecting the names it exported.
 * Returns { code, exports } where code is plain script-level JavaScript.
 */
export function stripModuleSyntax(source) {
  const lines = String(source).split('\n');
  const out = [];
  const exports = [];
  let index = 0;
  while (index < lines.length) {
    const line = lines[index];
    if (BUNDLE_SIDE_EFFECT.test(line)) {
      index += 1;
      continue;
    }
    if (BUNDLE_IMPORT_START.test(line)) {
      // Single-line import, or a braced list spread over several lines.
      if (BUNDLE_IMPORT_END.test(line)) {
        index += 1;
        continue;
      }
      index += 1;
      while (index < lines.length && !BUNDLE_IMPORT_END.test(lines[index])) index += 1;
      index += 1;
      continue;
    }
    const list = line.match(BUNDLE_EXPORT_LIST);
    if (list) {
      for (const raw of list[1].split(',')) {
        const name = raw.trim().split(/\s+as\s+/).pop();
        if (name) exports.push(name.trim());
      }
      index += 1;
      continue;
    }
    if (BUNDLE_EXPORT_DEFAULT.test(line)) {
      index += 1;
      continue;
    }
    const decl = line.match(BUNDLE_EXPORT_DECL);
    if (decl) {
      exports.push(decl[3]);
      out.push(line.replace(/export\s+/, ''));
      index += 1;
      continue;
    }
    out.push(line);
    index += 1;
  }
  return { code: out.join('\n'), exports };
}

/** Drop three.module.js's single trailing `export { ... };` statement. */
export function stripThreeExports(source) {
  const { code } = stripModuleSyntax(source);
  return code;
}

function bundle_iife(label, code, exports) {
  const unique = [...new Set(exports)];
  const returned = unique.length ? `\n  return { ${unique.join(', ')} };` : '';
  const binding = unique.length ? `const { ${unique.join(', ')} } = ` : '';
  return [
    `// ---- ${label} ----`,
    `${binding}(function () {`,
    code,
    `${returned}`,
    '})();',
  ].join('\n');
}

/**
 * Concatenate three.js, its addons and our runtime modules into one script.
 *
 * @param {object} input
 * @param {string} input.three            three.module.js source
 * @param {{name:string,source:string}[]} input.addons  in dependency order
 * @param {{name:string,source:string}[]} input.modules world/* sources, in order
 * @param {string} [input.entry]          trailing call, defaults to world_mount()
 */
export function bundleWebgl({ three, addons = [], modules = [], entry = 'world_mount();' }) {
  const pieces = [
    '// diorama world bundle — three.js (MIT) + addons + diorama runtime.',
    '// Generated by world/bundle.mjs; do not edit by hand.',
    '// ---- three.module.js ----',
    stripThreeExports(three),
  ];
  for (const addon of addons) {
    const { code, exports } = stripModuleSyntax(addon.source);
    pieces.push(bundle_iife(addon.name, code, exports));
  }
  const runtime = [];
  const runtimeExports = [];
  for (const mod of modules) {
    const { code, exports } = stripModuleSyntax(mod.source);
    runtime.push(`// ---- ${mod.name} ----`, code);
    runtimeExports.push(...exports);
  }
  pieces.push(bundle_iife('diorama runtime', `${runtime.join('\n')}\n${entry}`, []));
  void runtimeExports;
  return `${pieces.join('\n')}\n`;
}

